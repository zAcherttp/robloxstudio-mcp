// Vendors roblox-core's LESSONS.md into this package as a TypeScript module.
//
// The lessons are compiled in rather than read at runtime, because the server has to serve them
// on a machine that has the MCP installed and no framework checkout at all -- which is most
// machines. The cost is that this is a deliberate step: run it when the lessons change, and the
// commit shows exactly what an installed server will say.
//
//   node scripts/sync-core-lessons.mjs [path-to-roblox-core]
//
// Defaults to ../roblox-core, or ROBLOX_CORE_PATH.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const corePath = path.resolve(
  process.argv[2] ?? process.env.ROBLOX_CORE_PATH ?? path.resolve(repo, '..', 'roblox-core'),
);

const source = path.join(corePath, 'LESSONS.md');
if (!existsSync(source)) {
  console.error(`No LESSONS.md at ${source}`);
  console.error('Pass the roblox-core path, or set ROBLOX_CORE_PATH.');
  process.exit(1);
}

const lessons = readFileSync(source, 'utf8');
const rules = lessons.split('\n').filter((line) => /^[A-Z]{3,8} {2}/.test(line)).length;

const outDir = path.join(repo, 'packages', 'core', 'src', 'knowledge');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  path.join(outDir, 'lessons.ts'),
  `// Generated by scripts/sync-core-lessons.mjs from roblox-core/LESSONS.md. Do not edit.\n` +
    `// ${rules} lessons, synced ${new Date().toISOString().slice(0, 10)}.\n\n` +
    `export const CORE_LESSON_COUNT = ${rules};\n\n` +
    `export const CORE_LESSONS = ${JSON.stringify(lessons)};\n`,
  'utf8',
);
console.log(`Vendored ${rules} lessons from ${source}`);
